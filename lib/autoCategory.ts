// 長いキーワード優先（「ふらいぱん」が「ぱん」より先に判定される）
const ENTRIES = Object.entries(KEYWORDS).sort((a, b) => b[0].length - a[0].length);

/** 食材名からカテゴリを推測する。判定できなければ null */
export function guessCategory(name: string): string | null {
  const n = normalize(name);
  if (!n) return null;
  for (const [keyword, category] of ENTRIES) {
    if (n.includes(keyword)) return category;
  }
  return null;
}
