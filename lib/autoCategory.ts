// 表記ゆれ吸収: 全角英数→半角(NFKC)・カタカナ→ひらがな・空白除去
function normalize(input: string): string {
  return input
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[\s・･]/g, "")
    .replace(/[ァ-ヶ]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0x60));
}

